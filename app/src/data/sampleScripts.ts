export function parseCustomScript(text: string): Partial<ScriptExtraction> {
  const lines = text.split('\n').map((l) => l.trim()).filter(Boolean);
  
  // Try to find a scene heading
  const sceneLine = lines.find((l) => /^(INT\.|EXT\.|SCENE)/i.test(l)) || 'INT. SOUNDSTAGE - DAY';
  const sceneNumMatch = text.match(/SCENE\s*(\d+[A-Z]?)/i);
  const sceneNumber = sceneNumMatch ? `SCENE ${sceneNumMatch[1]}` : 'SCENE 01';

  // Find candidate prop words or uppercase action lines
  let detectedProp = 'Custom Production Hero Prop';
  const propMatches = text.match(/(?:DRAWS|REVEALS|HOLDS|PULLS|CARRIES|UNCLIPS|INSPECT)\s+(?:THE\s+)?([A-Z0-9\s\-]{3,35})/i);
  if (propMatches && propMatches[1]) {
    detectedProp = propMatches[1]
      .split(' ')
      .map((w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase())
      .join(' ')
      .replace(/^(The|A|An)\s+/i, '');
  }

  // Detect era/genre from text clues
  let world = 'Production Universe';
  let era = 'Contemporary Feature';
  if (/gilded|brass|astrolabe|steam|compass|aether/i.test(text)) {
    world = 'Aetheria';
    era = 'Gilded Steampunk / Victorian';
  } else if (/cyber|beryllium|terminal|neural|deck|airlock|reactor/i.test(text)) {
    world = 'Neo-Arcadia 2180';
    era = 'Hard Sci-Fi / Cyberpunk';
  } else if (/dagger|crypt|sarcophagus|altar|phial|gothic/i.test(text)) {
    world = 'The Obsidian Realm';
    era = 'Dark Gothic / Medieval Fantasy';
  } else if (/soviet|orient|protocol|chrono|vance|diplomatic/i.test(text)) {
    world = 'Europa Classified';
    era = 'Cold War Espionage (1960s)';
  }

  // Extract function on screen from action text
  const actionLines = lines.filter((l) => !l.startsWith('(') && l.length > 20 && !/^(INT|EXT|SCENE)/.test(l));
  const functionOnScreen = actionLines.slice(0, 2).join(' ') ||
    'Drawn during scene tension; inspected in close-up camera insert before critical dialogue.';

  // Extract constraints
  const constraints = 'Must fit in actor hand. Requires soft polyurethane stunt duplicate for impact safety. Matte anti-glare finish for studio lighting.';

  return {
    id: `custom-script-${Date.now()}`,
    title: 'Custom Screenplay Breakdown',
    sceneHeading: sceneLine,
    sceneNumber,
    propName: detectedProp,
    world,
    era,
    shortDescription: `Custom hero prop scripted for ${sceneNumber}. Designed for high-impact dramatic camera inserts.`,
    functionOnScreen,
    constraints,
    scriptText: text,
    suggestedMaterials: ['Machined aluminum / brass core', 'Hand-rubbed lacquer finish', 'Cast urethane stunt variant']
  };
}
